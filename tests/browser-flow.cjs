/* Executa contra um banco de teste; requer Chromium instalado ou SHKT_BROWSER_BIN. */
process.env.NODE_ENV='test';
process.env.DATABASE_URL=process.env.TEST_DATABASE_URL||'postgres://shkt:shkt@127.0.0.1:5432/shkt_erp_test';
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
(async()=>{
 const ambiente=await import('./ambiente.js');const {query,pool}=ambiente;
 await ambiente.prepararBanco();await ambiente.limparOperacional();
 await query('TRUNCATE tarefas_documentos,rascunhos_formulario');
 const usuario=await ambiente.usuarioTeste(),ref=await ambiente.referencias();
 const {gerarHash}=await import('../src/lib/auth.js');
 await query('UPDATE usuarios SET trocar_senha=false,senha_hash=$1 WHERE id=$2',[await gerarHash('TesteNavegador123!'),usuario.id]);
 await query(`INSERT INTO parametros(chave,valor,grupo) VALUES('onboarding.concluido','sim','SISTEMA') ON CONFLICT(chave) DO UPDATE SET valor='sim'`);
 const {criarApp}=await import('../src/server.js');
 const server=criarApp().listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
 const base=`http://127.0.0.1:${server.address().port}`;
 const browser=await chromium.launch({headless:true,executablePath:process.env.SHKT_BROWSER_BIN||undefined,args:['--no-sandbox','--no-zygote','--single-process','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});page.setDefaultTimeout(15000);
 const erros=[];page.on('pageerror',e=>erros.push(e.message));
 try{
  await page.goto(base+'/login');await page.locator('[name=email]').fill(usuario.email);await page.locator('[name=senha]').fill('TesteNavegador123!');
  await Promise.all([page.waitForURL('**/fluxo'),page.locator('button[type=submit]').click()]);
  assert.equal(await page.locator('.fluxo-passo').count(),8);
  await page.screenshot({path:'/tmp/shkt-desktop.png',fullPage:true});
  await page.goto(base+'/compras/novo');await page.getByText('Salvamento automático ativo',{exact:true}).waitFor();
  assert.equal(await page.locator('.rascunho-barra').count(),1,'um único autosave');
  await page.locator('[name=fornecedor_id]').selectOption(String(ref.fornecedorId));
  await page.locator('[data-etapa-avancar]').click();
  await page.locator('[name=item_produto_id]').selectOption(String(ref.produtoId));
  await page.locator('[name=item_unidade_id]').selectOption(String(ref.tonId));
  await page.locator('[name=item_quantidade]').fill('100');await page.locator('[name=item_preco]').fill('1500');
  await page.locator('[data-adicionar-linha]').click();
  await page.locator('[name=item_produto_id]').nth(1).selectOption(String(ref.produtoId));
  await page.locator('[name=item_quantidade]').nth(1).fill('50');await page.locator('[name=item_preco]').nth(1).fill('1700');
  await page.getByText('Rascunho salvo · pode continuar depois',{exact:true}).waitFor();
  await page.reload();await page.getByRole('button',{name:'Continuar rascunho'}).click();
  assert.equal(await page.locator('[name=item_quantidade]').count(),2);
  assert.equal(await page.locator('[name=item_quantidade]').nth(0).inputValue(),'100,000');
  assert.equal(await page.locator('[name=item_quantidade]').nth(1).inputValue(),'50,000');
  assert.equal(Number((await page.locator('[name=item_preco]').nth(1).inputValue()).replaceAll('.','').replace(',','.')),1700);
  assert.equal(await page.locator('form[data-rascunho]').getAttribute('data-etapa-atual'),'1');
  await page.locator('[data-etapa-avancar]').click();await page.locator('[name=local_entrega_id]').selectOption(String(ref.localId));
  await page.locator('[name=observacoes]').fill('Teste ponta a ponta · recuperação das duas linhas');
  await Promise.all([page.waitForURL(/\/compras\/\d+$/),page.locator('[data-etapa-gravar]').click()]);
  assert.equal((await query('SELECT * FROM rascunhos_formulario WHERE usuario_id=$1',[usuario.id])).rowCount,0,'rascunho limpo após gravar');
  const p=await query('SELECT * FROM pedidos_compra ORDER BY id DESC LIMIT 1');assert.equal(p.rows[0].valor_total,'235000.00');
  const {rows:itens}=await query('SELECT * FROM pedido_compra_itens WHERE pedido_id=$1',[p.rows[0].id]);assert.equal(itens.length,2);
  await page.locator('[data-gerar-pdf]').click();await page.getByRole('button',{name:'Ver meus arquivos'}).waitFor();
  const documentos=await import('../src/services/documentos.js');await documentos.processarUma();
  await page.getByRole('button',{name:'Ver meus arquivos'}).click();await page.waitForURL('**/documentos');
  const downloadPromise=page.waitForEvent('download');await page.getByRole('link',{name:'Baixar PDF'}).click();const download=await downloadPromise;
  await download.saveAs('/tmp/shkt-documento-teste.pdf');
  const bytes=await fs.readFile('/tmp/shkt-documento-teste.pdf');assert.equal(bytes.subarray(0,4).toString(),'%PDF');
  await page.setViewportSize({width:390,height:844});await page.goto(base+'/fluxo');await page.screenshot({path:'/tmp/shkt-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'sem rolagem horizontal no celular');
  await page.goto(base+'/compras/novo');assert.ok(await page.locator('[data-etapa-avancar]').isVisible());
  assert.deepEqual(erros,[]);console.log('Navegador: login → etapas → 2 itens → autosave → recuperação → gravação → PDF; desktop e celular OK.');
 }finally{await browser.close();await new Promise(r=>server.close(r));await pool.end();}
})().catch(e=>{console.error(e);process.exitCode=1;});
